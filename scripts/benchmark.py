#!/usr/bin/env python3
"""Measure optimized core or native desktop workloads and simultaneous Linux process-tree PSS."""
import argparse
import json
import os
import platform
import queue
import subprocess
import tempfile
import threading
import time
from pathlib import Path

REPOSITORY = Path(__file__).resolve().parents[1]


def command_output(command):
    try:
        return subprocess.check_output(
            command, text=True, stderr=subprocess.DEVNULL, timeout=3
        ).strip()
    except (OSError, subprocess.SubprocessError):
        return None


def machine_metadata():
    cpu = next(
        (
            line.split(':', 1)[1].strip()
            for line in Path('/proc/cpuinfo').read_text().splitlines()
            if line.startswith('model name')
        ),
        None,
    )
    memory = next(
        (
            line.split(':', 1)[1].strip()
            for line in Path('/proc/meminfo').read_text().splitlines()
            if line.startswith('MemTotal')
        ),
        None,
    )

    return {
        'system': platform.platform(),
        'cpu': cpu,
        'ram': memory,
        'revision': command_output(['git', '-C', str(REPOSITORY), 'rev-parse', 'HEAD']),
        'workingTreeDirty': bool(
            command_output(['git', '-C', str(REPOSITORY), 'status', '--porcelain'])
        ),
        'rust': command_output(['rustc', '--version']),
        'go': command_output(['go', '--version']),
        'node': command_output(['node', '--version']),
        'webkit': command_output(['pkg-config', '--modversion', 'webkit2gtk-4.1']),
        'wayland': bool(os.getenv('WAYLAND_DISPLAY')),
        'desktop': os.getenv('XDG_CURRENT_DESKTOP'),
        'hyprland': command_output(['hyprctl', 'version']),
        'cacheState': 'fresh analyzer and Rust index; existing Go toolchain and OS caches retained',
    }


def sample_tree(root_pid):
    """Sum PSS at one instant, including transient Go toolchain and WebKit children."""
    parents = {}
    for entry in Path('/proc').iterdir():
        if not entry.name.isdigit():
            continue
        try:
            stat = (entry / 'stat').read_text().rsplit(')', 1)[1].split()
            parents[int(entry.name)] = int(stat[1])
        except (OSError, IndexError, ValueError):
            continue

    descendants = {root_pid}
    while True:
        found = {pid for pid, parent in parents.items() if parent in descendants}
        if found <= descendants:
            break
        descendants |= found

    processes, unavailable = [], []
    for pid in sorted(descendants):
        try:
            fields = dict(
                line.split(':', 1)
                for line in Path(f'/proc/{pid}/smaps_rollup').read_text().splitlines()
                if ':' in line
            )
            pss = int(fields['Pss'].split()[0])
            command = Path(f'/proc/{pid}/comm').read_text().strip()
            processes.append({'pid': pid, 'name': command, 'pssKiB': pss})
        except (OSError, KeyError, ValueError):
            if Path(f'/proc/{pid}').exists():
                unavailable.append(pid)

    return {
        'totalPssKiB': sum(p['pssKiB'] for p in processes),
        'processes': processes,
        'unavailablePids': unavailable,
    }


def generate(root, count, functions):
    """Generate an owned temporary module; edits never touch the user's project."""
    root.mkdir()
    (root / '.sonar-benchmark-fixture').write_text(
        'Generated by Go Sonar benchmark harness\n'
    )
    (root / 'go.mod').write_text('module sonarbench\n\ngo 1.26.0\n')
    (root / 'leaf').mkdir()
    (root / 'leaf/leaf.go').write_text(
        'package leaf\n'
        'type Record struct { Value int }\n'
        'func Value() int { return 1 }\n'
    )

    previous = 'leaf'
    for index in reversed(range(count)):
        name = f'p{index:03d}'
        (root / name).mkdir()
        text = (
            f'package {name}\n'
            f'import "sonarbench/{previous}"\n'
            f'func Value() int {{ return {previous}.Value()+1 }}\n'
        )
        text += ''.join(
            f'func Transform{i}(v int) int {{ if v > {i} {{ return v+Value() }}; return v-{i} }}\n'
            for i in range(functions)
        )
        (root / name / 'part.go').write_text(text)
        previous = name

    (root / 'main.go').write_text(
        f'package sonarbench\n'
        f'import "sonarbench/{previous}"\n'
        f'func Get() int {{ return {previous}.Value() }}\n'
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--project', type=Path)
    parser.add_argument('--query', default='Get')
    parser.add_argument('--desktop', action='store_true')
    parser.add_argument(
        '--background-commit',
        action='store_true',
        help='Measure native layout and DOM commit without frame presentation; requires --desktop',
    )
    parser.add_argument('--generate-packages', type=int, default=0)
    parser.add_argument('--functions', type=int, default=30)
    parser.add_argument('--iterations', type=int, default=30)
    parser.add_argument(
        '--output', type=Path, default=REPOSITORY / 'benchmark-results/latest.json'
    )
    parser.add_argument('--timeout', type=float, default=180)
    args = parser.parse_args()

    if (
        not 1 <= args.iterations <= 1000
        or not 0 <= args.generate_packages <= 500
        or not 1 <= args.functions <= 500
    ):
        parser.error('iterations 1..1000, packages 0..500, functions 1..500 required')
    if args.project and args.generate_packages:
        parser.error('choose --project or --generate-packages')
    if args.background_commit and not args.desktop:
        parser.error('--background-commit requires --desktop')
    if args.timeout <= 0:
        parser.error('timeout must be positive')

    binary = REPOSITORY / (
        'target/release/go-sonar' if args.desktop else 'target/release/sonar-bench'
    )
    helper = (
        REPOSITORY / 'src-tauri/binaries/go-sonar-analyzer-x86_64-unknown-linux-gnu'
    )
    if not binary.is_file() or not helper.is_file():
        parser.error('build the release binary and helper first; see README')

    with tempfile.TemporaryDirectory(prefix='go-sonar-bench-') as temporary:
        temporary = Path(temporary)
        root = args.project.resolve() if args.project else REPOSITORY / 'fixtures/sample'
        if args.generate_packages:
            root = temporary / 'module'
            generate(root, args.generate_packages, args.functions)

        command = [
            str(binary),
            '--benchmark' if args.desktop else '--project',
            str(root),
            '--query',
            args.query,
            '--iterations',
            str(args.iterations),
        ]
        if args.background_commit:
            command.append('--background-commit')
        if not args.desktop:
            command += ['--analyzer', str(helper), '--cache', str(temporary / 'cache')]
            if args.generate_packages:
                command.append('--exercise-edits')

        environment = dict(
            os.environ,
            GO_SONAR_ANALYZER=str(helper),
            GO_SONAR_BENCHMARK_CACHE_DIR=str(temporary / 'cache'),
        )
        process = subprocess.Popen(
            command,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            env=environment,
            start_new_session=True,
        )
        events, errors, samples = [], [], []
        lines = queue.Queue(maxsize=100)

        def collect(stream, error=False):
            for line in stream:
                if error:
                    if len(errors) < 80:
                        errors.append(line.rstrip())
                    continue
                try:
                    lines.put(json.loads(line), timeout=1)
                except (ValueError, queue.Full):
                    continue

        readers = [
            threading.Thread(target=collect, args=(process.stdout,), daemon=True),
            threading.Thread(target=collect, args=(process.stderr, True), daemon=True),
        ]
        for reader in readers:
            reader.start()

        started, complete, timed_out, failed = time.monotonic(), False, False, False
        try:
            while True:
                samples.append({
                    'elapsedMs': (time.monotonic() - started) * 1000,
                    **sample_tree(process.pid),
                })

                while not lines.empty():
                    event = lines.get_nowait()
                    if not isinstance(event, dict):
                        continue
                    events.append(event)
                    report = event.get('report', event)
                    if report.get('phase') == 'complete':
                        complete = True
                    if report.get('phase') == 'failure':
                        failed = True

                if complete or failed or process.poll() is not None:
                    break
                if time.monotonic() - started > args.timeout:
                    timed_out = True
                    break
                time.sleep(0.025)
        finally:
            if process.poll() is None:
                import signal

                os.killpg(process.pid, signal.SIGTERM)
                try:
                    process.wait(timeout=5)
                except subprocess.TimeoutExpired:
                    os.killpg(process.pid, signal.SIGKILL)
            process.wait()
            for reader in readers:
                reader.join(timeout=1)
            while not lines.empty():
                events.append(lines.get_nowait())

        complete = complete or any(
            e.get('report', e).get('phase') == 'complete' for e in events
        )
        observed_names = sorted({p['name'] for s in samples for p in s['processes']})
        peak = max(samples, key=lambda s: s['totalPssKiB'], default={})

        mode = 'headless'
        presentation_requested = None
        if args.desktop:
            mode = 'desktop-background' if args.background_commit else 'desktop'
            presentation_requested = 'commit' if args.background_commit else 'frames'

        frame_presentation_observed = any(
            event.get('report', {}).get('phase') == 'complete'
            and event.get('report', {}).get('presentation') == 'frames'
            for event in events
        )
        webview_observed = any(
            'WebKit' in name or 'WebProcess' in name for name in observed_names
        )

        result = {
            'mode': mode,
            'releaseBuild': True,
            'presentationRequested': presentation_requested,
            'framePresentationObserved': frame_presentation_observed,
            'machine': machine_metadata(),
            'workload': {
                'generatedPackages': args.generate_packages,
                'functionsPerPackage': args.functions if args.generate_packages else None,
                'project': str(root),
            },
            'complete': complete,
            'timedOut': timed_out,
            'exitCode': process.returncode,
            'elapsedMs': (time.monotonic() - started) * 1000,
            'events': events,
            'memory': {
                'metric': 'simultaneous process-tree PSS',
                'samplingIntervalMs': 25,
                'peak': peak,
                'observedProcesses': observed_names,
                'webViewObserved': webview_observed,
                'samples': samples,
            },
            'stderr': errors,
        }

        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(json.dumps(result, indent=2) + '\n')
        print(json.dumps({
            'output': str(args.output),
            'complete': complete,
            'peakPssKiB': peak.get('totalPssKiB'),
            'webViewObserved': result['memory']['webViewObserved'],
        }))

        if not complete or timed_out:
            raise SystemExit(1)


if __name__ == '__main__':
    main()
